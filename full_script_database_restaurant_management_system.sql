CREATE OR REPLACE VIEW detailed_orders_view AS
SELECT 
    o.order_id, o.order_number, l.name AS location_name,
    c.first_name || ' ' || COALESCE(c.last_name, '') AS customer_name,
    c.phone AS customer_phone, o.order_type, o.status AS order_status,
    m.name AS item_name, oi.quantity, oi.item_price,
    (oi.quantity * oi.item_price) AS line_price, o.total_order_amount
FROM orders o
JOIN locations l ON o.location_id = l.location_id
JOIN customers c ON o.customer_id = c.customer_id
JOIN order_items oi ON o.order_id = oi.order_id
JOIN menu_items m ON oi.menu_item_id = m.menu_item_id;

CREATE OR REPLACE VIEW shift_details_view AS
SELECT
    sh.shift_id, sh.location_id, l.name AS location_name,
    sh.staff_id, st.last_name || ' ' || st.first_name AS employee,
    st.position, sh.start_time, sh.end_time, sh.actual_start_time,
    sh.actual_end_time, sh.break_time_minutes, sh.status,
    ROUND((EXTRACT(EPOCH FROM (sh.end_time - sh.start_time)) / 3600)::numeric, 2) AS planned_hours,
    ROUND((EXTRACT(EPOCH FROM (sh.actual_end_time - sh.actual_start_time)) / 3600 - sh.break_time_minutes / 60.0)::numeric, 2) AS worked_hours
FROM shift_schedules sh
JOIN staff st ON st.staff_id = sh.staff_id
JOIN locations l ON l.location_id = sh.location_id;


