CREATE OR REPLACE FUNCTION calculate_order_total(p_order_id BIGINT)
RETURNS numeric(10,2) LANGUAGE plpgsql AS $$
DECLARE
    v_total numeric(10,2);
BEGIN
    SELECT COALESCE(SUM(quantity * item_price), 0) INTO v_total
    FROM order_items WHERE order_id = p_order_id;
    RETURN v_total;
END;
$$;

CREATE OR REPLACE FUNCTION is_stock_critical(p_location_id BIGINT, p_ingredient_id BIGINT)
RETURNS boolean LANGUAGE plpgsql AS $$
DECLARE
    v_is_critical boolean;
BEGIN
    SELECT (current_stock <= min_stock_level) INTO v_is_critical
    FROM location_inventory WHERE location_id = p_location_id AND ingredient_id = p_ingredient_id;
    RETURN COALESCE(v_is_critical, false);
END;
$$;

CREATE OR REPLACE PROCEDURE receive_inventory(
    p_location_id BIGINT, p_ingredient_id BIGINT, p_quantity_added numeric
)
LANGUAGE plpgsql AS $$
BEGIN
    IF p_quantity_added <= 0 THEN
        RAISE EXCEPTION 'Quantity added must be greater than 0.';
    END IF;
    UPDATE location_inventory
    SET current_stock = current_stock + p_quantity_added
    WHERE location_id = p_location_id AND ingredient_id = p_ingredient_id;
END;
$$;


